"""Synchronize the documented tool table with generated tool metadata."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from score_tools.catalog import load_environments, validate_catalog

TOOLS_DIR = Path(__file__).resolve().parent.parent
README_PATH = TOOLS_DIR / "README.md"
TABLE_START = "<!-- BEGIN GENERATED TOOL TABLE -->"
TABLE_END = "<!-- END GENERATED TOOL TABLE -->"


def _render_table(tools, environments):
    rows = [
        TABLE_START,
        "<!-- Generated by internal/sync_readme.py; do not edit manually. -->",
        "",
        "| Tool / purpose | Provider / policy | Version request | Environments | Platforms | Update owner | Version source |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name, definition in sorted(tools.items()):
        selected = [
            env
            for env, selections in environments.items()
            if any(name in names for names in selections.values())
        ]
        if "config" in definition:
            selected.append(
                "published image"
                if definition["config"].startswith("src/")
                else "repository"
            )
        version = definition.get("version", "distribution/latest")
        if "compatibility_version" in definition:
            version += " (compatibility: " + definition["compatibility_version"] + ")"
        rows.append(
            f"| `{name}` — {definition['description']} | {definition['provider']} / {definition['policy']} | {version} | "
            + (", ".join(selected) or definition.get("phase", "setup"))
            + " | "
            + ", ".join(definition["platforms"])
            + " | "
            + definition["update"]
            + " | [definition]("
            + (
                definition["source"].removeprefix("tools/")
                if definition["source"].startswith("tools/")
                else "../" + definition["source"]
            )
            + ") |"
        )
    rows.extend(
        [
            "",
            "Native tools support container and Bazel delivery; Python tools additionally support standalone uv.",
            "Other providers are container/setup-specific. The published image combines s-core-local and bazel-feature.",
            "External bundles and base images retain their native config and lock ownership (see the architecture document).",
            "",
            TABLE_END,
        ]
    )
    return "\n".join(rows)


def _updated_readme(content: str, table: str) -> str:
    if content.count(TABLE_START) != 1 or content.count(TABLE_END) != 1:
        raise SystemExit(
            f"{README_PATH.name} must contain exactly one generated tool table"
        )

    start = content.index(TABLE_START)
    end = content.index(TABLE_END, start) + len(TABLE_END)
    return content[:start] + table + content[end:]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Synchronize README tool versions with lockfiles.",
    )
    parser.add_argument(
        "--check", action="store_true", help="Fail on stale generated inventory."
    )
    args = parser.parse_args(argv)

    current = README_PATH.read_text(encoding="utf-8")
    table = _render_table(validate_catalog(), load_environments())
    expected = _updated_readme(current, table)

    if current == expected:
        return 0

    if args.check:
        print("Generated tool inventory is stale", file=sys.stderr)
        return 1
    README_PATH.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
